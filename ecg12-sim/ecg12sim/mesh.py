"""Anatomically accurate ventricular mesh loading.

Reads the legacy-ASCII VTK unstructured grids published as the *virtual cohort
of adult healthy four-chamber heart meshes from CT images*
(Rodero et al., CC-BY-4.0, https://doi.org/10.5281/zenodo.4590293) and reduces
one to the part this project simulates: left- and right-ventricular myocardium,
with fibre architecture and universal ventricular coordinates attached.

Why a hand-written parser instead of ``meshio``: the cohort uses exactly one
format, the file is a quarter of a gigabyte of ASCII, and reading it needs a
single streaming pass rather than a general-purpose reader. That keeps the
project's dependencies at numpy + matplotlib.

What the cohort provides, and what it is used for here
------------------------------------------------------

``CELL_DATA  SCALARS ID``
    Tissue tag per tetrahedron. Tag 1 is LV myocardium and tag 2 is RV
    myocardium; tags 3-24 are atria, vessel walls, valve planes and vein inlets,
    all discarded.
``CELL_DATA  VECTORS fibres`` / ``VECTORS sheets``
    Local myocyte fibre and sheet directions, giving the orthotropic basis that
    an anisotropic conduction tensor needs. Generated by a rule-based method
    (80 degrees at endocardium to -60 degrees at epicardium), so the fibre
    architecture is anatomically *realistic* rather than measured per subject;
    the geometry itself is image-derived.
``POINT_DATA  RHO / PHI / Z / V``
    Universal ventricular coordinates: transmural depth (0 endocardium ->
    1 epicardium), rotational angle, apico-basal height (0 apex -> 1 base) and
    intra-ventricular side (-1 LV, +1 RV). Non-ventricular nodes carry -10.

RHO is the principled replacement for the 1-D strand's ``frac = i/(n_cells-1)``
index heuristic: it gives a true transmural depth at every node, so endo / M /
epi heterogeneity can be assigned anywhere in a 3-D wall.

Note on file layout: the published description lists ``CELLS`` before
``CELL_TYPES``, but the actual files emit ``CELL_TYPES`` first. The parser is
therefore order-agnostic and keys off section headers rather than position.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from itertools import islice

import numpy as np

from . import ionic_model as im

# Tissue tags used by the Rodero cohort.
TAG_LV_MYO = 1
TAG_RV_MYO = 2
VENTRICULAR_TAGS = (TAG_LV_MYO, TAG_RV_MYO)

# Sentinel the cohort writes into the UVC fields for non-ventricular nodes.
UVC_UNDEFINED = -10.0

MM_PER_CM = 10.0

# Transmural depth bands, matching the endo/mid/epi split that
# ``ecg12sim.cable._region_scales`` applies along the 1-D strand.
RHO_ENDO_MAX = 0.30
RHO_MID_MAX = 0.60

_CACHE_VERSION = 1


@dataclass
class VentricularMesh:
    """Biventricular myocardium reduced from a four-chamber cohort mesh.

    Coordinates are in **cm** (the cohort stores mm) to match the convention
    used throughout :mod:`ecg12sim`.
    """

    points: np.ndarray        # (n_nodes, 3) cm
    tets: np.ndarray          # (n_tets, 4) int node indices
    tags: np.ndarray          # (n_tets,) 1 = LV myo, 2 = RV myo
    fibres: np.ndarray        # (n_tets, 3) unit vectors
    sheets: np.ndarray        # (n_tets, 3) unit vectors
    rho: np.ndarray           # (n_nodes,) 0 = endo, 1 = epi
    phi: np.ndarray           # (n_nodes,) rotational coordinate
    z: np.ndarray             # (n_nodes,) 0 = apex, 1 = base
    v: np.ndarray             # (n_nodes,) -1 = LV, +1 = RV
    source: str = ""          # provenance, for citation

    @property
    def n_nodes(self) -> int:
        return int(self.points.shape[0])

    @property
    def n_tets(self) -> int:
        return int(self.tets.shape[0])

    @property
    def extent_cm(self) -> np.ndarray:
        """Bounding-box size in cm, as (dx, dy, dz)."""
        return self.points.max(axis=0) - self.points.min(axis=0)

    def region(self) -> np.ndarray:
        """Per-node endo / mid / epi code derived from transmural depth."""
        return region_from_rho(self.rho)

    def tet_volumes_cm3(self) -> np.ndarray:
        """Signed-magnitude tetrahedron volumes in cm^3.

        Promoted to float64: the triple product of float32 edge vectors loses
        too much precision on sub-millimetre tetrahedra.
        """
        p = self.points[self.tets].astype(np.float64)   # (n_tets, 4, 3)
        a = p[:, 1] - p[:, 0]
        b = p[:, 2] - p[:, 0]
        c = p[:, 3] - p[:, 0]
        return np.abs(np.einsum("ij,ij->i", np.cross(a, b), c)) / 6.0

    def summary(self) -> str:
        vols = self.tet_volumes_cm3()
        ext = self.extent_cm
        reg = self.region()
        n_lv = int((self.tags == TAG_LV_MYO).sum())
        n_rv = int((self.tags == TAG_RV_MYO).sum())
        # Representative edge length of a regular tet of the median volume.
        edge_mm = (float(np.median(vols)) * 6.0 * np.sqrt(2.0)) ** (1.0 / 3.0) * MM_PER_CM
        L = [
            "Ventricular mesh",
            f"  source              : {self.source or 'unknown'}",
            f"  nodes / tetrahedra  : {self.n_nodes:,} / {self.n_tets:,}",
            f"  LV / RV tetrahedra  : {n_lv:,} / {n_rv:,}",
            f"  bounding box (cm)   : {ext[0]:.1f} x {ext[1]:.1f} x {ext[2]:.1f}",
            f"  myocardial volume   : {vols.sum():.1f} cm^3",
            f"  median tet edge     : {edge_mm:.2f} mm",
            f"  RHO range           : {self.rho.min():.3f} - {self.rho.max():.3f}",
            f"  Z range             : {self.z.min():.3f} - {self.z.max():.3f}",
            f"  nodes endo/mid/epi  : {int((reg == im.ENDO).sum()):,} / "
            f"{int((reg == im.MID).sum()):,} / {int((reg == im.EPI).sum()):,}",
        ]
        return "\n".join(L)


def region_from_rho(rho: np.ndarray) -> np.ndarray:
    """Map transmural depth to endo / mid / epi codes.

    Uses the same band edges as the 1-D strand so that transmural heterogeneity
    is specified identically in both models.
    """
    reg = np.full(np.shape(rho), im.EPI, dtype=int)
    reg[np.asarray(rho) < RHO_MID_MAX] = im.MID
    reg[np.asarray(rho) < RHO_ENDO_MAX] = im.ENDO
    return reg


# ---------------------------------------------------------------------------
# Legacy ASCII VTK parsing
# ---------------------------------------------------------------------------

def _read_floats(fh, n_lines: int, per_line: int) -> np.ndarray:
    """Consume ``n_lines`` whitespace-separated numeric lines into an array."""
    chunk = "".join(islice(fh, n_lines))
    arr = np.fromstring(chunk, sep=" ")
    expected = n_lines * per_line
    if arr.size != expected:
        raise ValueError(
            f"expected {expected} values across {n_lines} lines, got {arr.size}")
    return arr.reshape(n_lines, per_line) if per_line > 1 else arr


def parse_vtk(path: str) -> dict:
    """Stream a legacy ASCII VTK unstructured grid into raw arrays.

    Returns a dict with ``points``, ``tets``, ``cell_types`` and whatever
    ``CELL_DATA`` / ``POINT_DATA`` fields the file carries. Section order is not
    assumed.
    """
    out: dict = {}
    n_cells = None
    scope = None            # "cell" or "point", for naming data arrays

    with open(path, "r") as fh:
        header = fh.readline()
        if "vtk DataFile" not in header:
            raise ValueError(f"{path}: not a legacy VTK file")
        fh.readline()                                   # title
        fmt = fh.readline().strip().upper()
        if fmt != "ASCII":
            raise ValueError(f"{path}: only ASCII VTK is supported, found {fmt}")
        dataset = fh.readline().strip().upper()
        if "UNSTRUCTURED_GRID" not in dataset:
            raise ValueError(f"{path}: expected UNSTRUCTURED_GRID, found {dataset}")

        while True:
            line = fh.readline()
            if not line:
                break
            parts = line.split()
            if not parts:
                continue
            key = parts[0].upper()

            if key == "POINTS":
                n_pts = int(parts[1])
                out["points"] = _read_floats(fh, n_pts, 3)

            elif key == "CELL_TYPES":
                n = int(parts[1])
                out["cell_types"] = _read_floats(fh, n, 1).astype(np.int8)

            elif key == "CELLS":
                n_cells = int(parts[1])
                # Every cell is a tetrahedron, so each line is "4 i j k l".
                block = _read_floats(fh, n_cells, 5)
                if not np.all(block[:, 0] == 4):
                    raise ValueError(f"{path}: found non-tetrahedral cells")
                out["tets"] = block[:, 1:].astype(np.int32)

            elif key == "CELL_DATA":
                scope = "cell"
                n_cells = int(parts[1])

            elif key == "POINT_DATA":
                scope = "point"

            elif key == "SCALARS":
                name = parts[1]
                n = n_cells if scope == "cell" else out["points"].shape[0]
                fh.readline()                           # LOOKUP_TABLE line
                out[f"{scope}:{name}"] = _read_floats(fh, n, 1)

            elif key == "VECTORS":
                name = parts[1]
                n = n_cells if scope == "cell" else out["points"].shape[0]
                out[f"{scope}:{name}"] = _read_floats(fh, n, 3)

    for required in ("points", "tets"):
        if required not in out:
            raise ValueError(f"{path}: missing {required.upper()} section")
    return out


def _pick(raw: dict, scope: str, *candidates: str) -> np.ndarray | None:
    """Find a data array by name, tolerating the cohort's ``.dat`` suffixes."""
    for cand in candidates:
        for key, val in raw.items():
            if not key.startswith(f"{scope}:"):
                continue
            name = key.split(":", 1)[1]
            if name.lower().replace(".dat", "") == cand.lower():
                return val
    return None


def extract_ventricles(raw: dict, tags: tuple[int, ...] = VENTRICULAR_TAGS,
                       source: str = "") -> VentricularMesh:
    """Reduce a parsed four-chamber mesh to ventricular myocardium.

    Keeps only tetrahedra carrying one of ``tags``, drops now-unreferenced
    nodes, and renumbers the connectivity compactly.
    """
    tet_tags = _pick(raw, "cell", "ID", "id")
    if tet_tags is None:
        raise ValueError("mesh has no CELL_DATA 'ID' tag array")
    tet_tags = tet_tags.astype(int)

    keep = np.isin(tet_tags, tags)
    if not keep.any():
        raise ValueError(f"no tetrahedra carry tags {tags}")

    tets = raw["tets"][keep]
    used, remapped = np.unique(tets, return_inverse=True)
    tets = remapped.reshape(tets.shape).astype(np.int32)

    fibres = _pick(raw, "cell", "fibres", "fiber", "fibers")
    sheets = _pick(raw, "cell", "sheets", "sheet")
    n_kept = int(keep.sum())
    fibres = fibres[keep] if fibres is not None else np.zeros((n_kept, 3))
    sheets = sheets[keep] if sheets is not None else np.zeros((n_kept, 3))

    def _uvc(*names) -> np.ndarray:
        arr = _pick(raw, "point", *names)
        out = arr[used] if arr is not None else np.full(used.size, np.nan)
        return out.astype(np.float32)

    # The VTK header declares POINTS/VECTORS as `float`, so the source data is
    # single precision. Storing float64 would inflate the cache and overstate
    # the precision actually present.
    return VentricularMesh(
        points=(raw["points"][used] / MM_PER_CM).astype(np.float32),   # mm -> cm
        tets=tets,
        tags=tet_tags[keep].astype(np.int8),
        fibres=fibres.astype(np.float32),
        sheets=sheets.astype(np.float32),
        rho=_uvc("RHO"),
        phi=_uvc("PHI"),
        z=_uvc("Z"),
        v=_uvc("V"),
        source=source,
    )


# ---------------------------------------------------------------------------
# Caching
# ---------------------------------------------------------------------------

_FIELDS = ("points", "tets", "tags", "fibres", "sheets", "rho", "phi", "z", "v")


def save_cache(mesh: VentricularMesh, path: str) -> None:
    """Write the reduced mesh to a compressed ``.npz``."""
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    np.savez_compressed(
        path, _version=np.array([_CACHE_VERSION]),
        _source=np.array([mesh.source]),
        **{f: getattr(mesh, f) for f in _FIELDS})


def load_cache(path: str) -> VentricularMesh:
    """Read a reduced mesh written by :func:`save_cache`."""
    with np.load(path, allow_pickle=False) as z:
        version = int(z["_version"][0]) if "_version" in z else 0
        if version != _CACHE_VERSION:
            raise ValueError(f"{path}: cache version {version}, "
                             f"expected {_CACHE_VERSION}")
        source = str(z["_source"][0]) if "_source" in z else ""
        return VentricularMesh(source=source, **{f: z[f] for f in _FIELDS})


def load_ventricular_mesh(vtk_path: str, cache_path: str | None = None,
                          rebuild: bool = False) -> VentricularMesh:
    """Load ventricular myocardium, using a cached reduction when available.

    The first call streams the full four-chamber ASCII VTK (a quarter of a
    gigabyte) and writes a compact cache beside it; later calls read the cache.
    """
    if cache_path is None:
        cache_path = os.path.splitext(vtk_path)[0] + ".ventricles.npz"

    if not rebuild and os.path.exists(cache_path):
        return load_cache(cache_path)

    raw = parse_vtk(vtk_path)
    mesh = extract_ventricles(raw, source=os.path.basename(vtk_path))
    save_cache(mesh, cache_path)
    return mesh


