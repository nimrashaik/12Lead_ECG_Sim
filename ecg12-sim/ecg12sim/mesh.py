def _md5(path: str, chunk: int = 1 << 20) -> str:
    import hashlib
    h = hashlib.md5()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(chunk), b""):
            h.update(block)
    return h.hexdigest()


def fetch_mesh(case: str = "01", dest_dir: str = "data/meshes",
               verify: bool = True) -> str:
    """Download and extract one cohort mesh, returning the path to its ``.vtk``.

    The archives are 54-103 MB each and expand to roughly 250 MB of ASCII, so
    they are fetched on demand rather than committed. Downloads are checked
    against the record's published MD5 unless ``verify`` is False.
    """
    import tarfile
    import urllib.request

    case = str(case).zfill(2)
    if case not in COHORT_MD5:
        raise ValueError(f"unknown case {case!r}; expected one of "
                         f"{sorted(COHORT_MD5)}")

    os.makedirs(dest_dir, exist_ok=True)
    vtk_path = os.path.join(dest_dir, f"{case}.vtk")
    if os.path.exists(vtk_path):
        return vtk_path

    archive = os.path.join(dest_dir, f"{case}.tar.gz")
    if not os.path.exists(archive):
        url = ZENODO_URL.format(record=ZENODO_RECORD, name=f"{case}.tar.gz")
        urllib.request.urlretrieve(url, archive)

    if verify:
        got = _md5(archive)
        if got != COHORT_MD5[case]:
            raise ValueError(
                f"{archive}: MD5 mismatch (got {got}, "
                f"expected {COHORT_MD5[case]}); refusing to use it")

    with tarfile.open(archive, "r:gz") as tf:
        members = [m for m in tf.getmembers() if m.name.endswith(".vtk")]
        if not members:
            raise ValueError(f"{archive}: contains no .vtk file")
        # Guard against path traversal in the archive.
        for m in members:
            if os.path.isabs(m.name) or ".." in m.name.split("/"):
                raise ValueError(f"{archive}: unsafe member path {m.name!r}")
        tf.extractall(dest_dir, members=members)

    extracted = os.path.join(dest_dir, members[0].name)
    if extracted != vtk_path:
        os.replace(extracted, vtk_path)
    return vtk_path
